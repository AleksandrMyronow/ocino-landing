/**
 * Pricing — конфіг блоку вартості послуг.
 *
 * Структура з двох рівнів:
 * - simpleItems: прості позиції з однією ціною (відображаються картками 3×N)
 * - tieredItems: позиції з кількома градаціями (відображаються широкими картками)
 *
 * Категорія слугує для групування на сторінці і необов'язкова — можна
 * залишити всі прості позиції в одній великій сітці.
 */

export interface PricingTier {
    /** Опис категорії (для tieredItems) */
    label: string;
    /** Ціна для цієї категорії */
    price: string;
  }
  
  export interface PricingSimpleItem {
    /** ID для key */
    id: string;
    /** Іконка (emoji або символ) */
    icon: string;
    /** Назва послуги */
    title: string;
    /** Опціональний підзаголовок */
    subtitle?: string;
    /** Ціна "від X грн" */
    price: string;
  }
  
  export interface PricingTieredItem {
    /** ID для key */
    id: string;
    /** Іконка */
    icon: string;
    /** Назва послуги */
    title: string;
    /** Опціональний опис */
    description?: string;
    /** Градації цін */
    tiers: PricingTier[];
  }
  
