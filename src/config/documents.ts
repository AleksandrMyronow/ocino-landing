/**
 * Документи для оцінки за типами майна.
 * Структура з трьох можливих формувань для кожного типу:
 * - required: основний список (завжди потрібний)
 * - subgroups: підблоки (наприклад, "Для торгових марок" / "Для патентів" / "Для ПЗ")
 * - conditionalGroups: додаткові умовні групи (наприклад, "Для активної діяльності")
 *
 * Тип може мати будь-яку комбінацію цих полів.
 * Спільні для всіх трьох компаній (вони оцінюють усе майно).
 */
export interface DocumentSubgroup {
  /** Назва підблоку, що показується перед списком */
  title: string;
  /** Документи у цьому підблоці */
  items: string[];
}

export interface ConditionalGroup {
  /** Опис умови, наприклад "Для активної господарської діяльності" */
  condition: string;
  /** Документи, що потрібні за цією умовою */
  items: string[];
}

export interface DocumentGroup {
  id: string;
  title: string;
  /** Основний обов'язковий список. Якщо є subgroups — може бути відсутнім. */
  required?: string[];
  /** Підблоки (для типів, що мають кілька рівнозначних варіантів) */
  subgroups?: DocumentSubgroup[];
  /** Додаткові умовні групи (наприклад, для бізнесу) */
  conditionalGroups?: ConditionalGroup[];
}

